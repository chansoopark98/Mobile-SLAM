#!/usr/bin/env python3
"""Write third_party/libcxx_compat/include/libcxx_compat/__algorithm/sort_llvm14.h: the libc++ 14 std::sort
(introsort) and the heap helpers its depth-limit fallback calls, excerpted from the installed
libc++-14-dev headers, in namespace slam_refact::libcxx::llvm14. Algorithm lines are copied verbatim;
only qualifiers and attribute macros are rewritten (listed in the file header).

  python3 -I tools/gen_libcxx14_sort_excerpt.py third_party/libcxx_compat/include/libcxx_compat/__algorithm/sort_llvm14.h
"""
import re
import sys

SRC = '/usr/lib/llvm-14/include/c++/v1/__algorithm/'
out_path = sys.argv[1]


def lines(name):
    return open(SRC + name).read().split('\n')


def grab(name, start_pat, end_pat):
    """Lines from the template line before the first line matching start_pat through end_pat."""
    ls = lines(name)
    i = next(k for k, l in enumerate(ls) if re.search(start_pat, l))
    while not ls[i].startswith('template'):
        i -= 1
    j = next(k for k in range(i, len(ls)) if re.search(end_pat, ls[k]))
    return ls[i:j + 1]


def fn(name, fname):
    """A whole function definition: from its template line to the closing brace at column 0."""
    ls = lines(name)
    k = next(k for k, l in enumerate(ls) if re.match(r'^%s\(' % re.escape(fname), l) or re.match(r'^\w.*\b%s\(' % re.escape(fname), l))
    i = k
    while not ls[i].startswith('template'):
        i -= 1
    j = next(m for m in range(k, len(ls)) if ls[m].startswith('}'))
    return ls[i:j + 1]


parts = []
parts += fn('sort.h', '__sort3') + ['']
parts += fn('sort.h', '__sort4') + ['']
parts += fn('sort.h', '__sort5') + ['']
parts += fn('sift_down.h', '__sift_down') + ['']
parts += fn('make_heap.h', '__make_heap') + ['']
parts += fn('pop_heap.h', '__pop_heap') + ['']
parts += fn('sort_heap.h', '__sort_heap') + ['']
parts += fn('partial_sort.h', '__partial_sort') + ['']
parts += fn('sort.h', '__insertion_sort_3') + ['']
parts += fn('sort.h', '__insertion_sort_incomplete') + ['']
parts += fn('sort.h', '__introsort') + ['']
parts += fn('sort.h', '__log2i') + ['']
parts += fn('sort.h', '__sort') + ['']

body = '\n'.join(parts)
repl = [
    (r'_VSTD::move\(', 'std::move('),
    (r'_VSTD::', '::slam_refact::libcxx::llvm14::'),
    (r'\b_LIBCPP_CONSTEXPR_AFTER_CXX11 ', ''), (r'\b_LIBCPP_CONSTEXPR_AFTER_CXX17 ', ''),
    (r'^_LIBCPP_CONSTEXPR_AFTER_CXX11 ', ''), (r'^_LIBCPP_CONSTEXPR_AFTER_CXX17 ', ''),
    (r'\binline _LIBCPP_HIDE_FROM_ABI ', 'inline '), (r'^_LIBCPP_HIDDEN\n', ''),
    (r'^inline _LIBCPP_INLINE_VISIBILITY ', 'inline '),
    (r'\biterator_traits<', 'std::iterator_traits<'),
    (r'\bis_trivially_copy_constructible<', 'std::is_trivially_copy_constructible<'),
    (r'\bis_trivially_copy_assignable<', 'std::is_trivially_copy_assignable<'),
    (r'(?<![\w:])swap\(', 'std::swap('),
]
for a, b in repl:
    body = re.sub(a, b, body, flags=re.M)
body = re.sub(r'^_LIBCPP_CONSTEXPR_AFTER_CXX1[17]\n', '', body, flags=re.M)
body = re.sub(r'^_LIBCPP_CONSTEXPR_AFTER_CXX1[17] ', '', body, flags=re.M)
body = re.sub(r'^inline _LIBCPP_INLINE_VISIBILITY\n', 'inline\n', body, flags=re.M)
body = re.sub(r'^inline _LIBCPP_CONSTEXPR_AFTER_CXX1[17]\n', 'inline\n', body, flags=re.M)
assert '_LIBCPP' not in body, [l for l in body.split('\n') if '_LIBCPP' in l]

head = '''//===----------------------------------------------------------------------===//
//
// Part of the LLVM Project, under the Apache License v2.0 with LLVM Exceptions.
// See https://llvm.org/LICENSE.txt for license information.
// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception
//
//===----------------------------------------------------------------------===//
// libcxx_compat: libc++ 14 std::sort (introsort with the heap-sort depth fallback), excerpted from
// libc++-14-dev 1:14.0.0-1ubuntu1.1 (/usr/lib/llvm-14/include/c++/v1/__algorithm/{sort,sift_down,
// make_heap,pop_heap,sort_heap,partial_sort}.h), in namespace slam_refact::libcxx::llvm14.
//
// Why: the original xr-slam.wasm sorts with this algorithm, not with the pdq-style sort of the emsdk
// 5.0.0 libc++ (LLVM 21) the rest of libcxx_compat follows. f1555 (SelectSubset score sort) has
// the libc++ 14 structure (length <= 30 insertion sort, median of 3 / of 5 at >= 1000, equal-to-
// pivot partition, __insertion_sort_incomplete, heap fallback with swap + sift_down), and run in
// isolation it reproduces libc++ 14 std::sort exactly (150/150 cases incl. the engine's scores),
// while the LLVM 21 sort differs on 15/18 engine score vectors (build/slam-refact-20261016/
// precision/). libc++ 14 and 21 give equal results for the other excerpted algorithms except
// nth_element (8/56 golden cases), which stays LLVM 21 here (not verified against the original).
//
// Generated by tools/gen_libcxx14_sort_excerpt.py: algorithm lines verbatim;
// rewritten: _VSTD::move -> std::move, other _VSTD:: -> ::slam_refact::libcxx::llvm14::, constexpr/visibility attribute macros
// dropped, iterator_traits / is_trivially_copy_* / swap qualified with std::.
#ifndef SLAM_REFACT_LIBCXX_COMPAT___ALGORITHM_SORT_LLVM14_H
#define SLAM_REFACT_LIBCXX_COMPAT___ALGORITHM_SORT_LLVM14_H

#include <iterator>
#include <type_traits>
#include <utility>

namespace slam_refact {
namespace libcxx {
namespace llvm14 {

'''
tail = '''
// Public entry (libc++ 14 sort.h): _Comp_ref = _Compare& (no debug comparator), __unwrap_iter does
// not change the order and is omitted.
template <class _RandomAccessIterator, class _Compare>
inline void sort(_RandomAccessIterator __first, _RandomAccessIterator __last, _Compare __comp) {
  ::slam_refact::libcxx::llvm14::__sort<_Compare&>(__first, __last, __comp);
}

}  // namespace llvm14
}  // namespace libcxx
}  // namespace slam_refact

#endif  // SLAM_REFACT_LIBCXX_COMPAT___ALGORITHM_SORT_LLVM14_H
'''
open(out_path, 'w').write(head + body + '\n' + tail)
print('wrote', out_path)
