// MB-TRI input generator (architecture.md §6.6.3, S3 §8.1).
//
// probes/triangulate-r1/result.json (original func 1613 outputs, 128 cases) does not store its
// inputs. This script regenerates them with the exact generator of
// slam_refact/tools/re/spec_map_builder/triangulate_probe.mjs (mulberry32 seed 20261015, 64
// vectors) and proves they are the same inputs: the public reference formula evaluated on them
// must reproduce every refR/refJ of result.json bit for bit. Only then cases.tsv is written.
//
// cases.tsv: k <tab> ray[2] <tab> projection[12] <tab> point[3]; every double as its IEEE-754
// bit pattern in 16 hex digits.
//
// Usage (cwd = repo root):
//   node slam_refact/engine/tests/map_builder/gen_triangulate_cases.mjs \
//     --result slam_refact/engine/tests/data/map-builder/probes/triangulate-r1/result.json \
//     --output slam_refact/engine/tests/data/map-builder/probes/triangulate-r1/cases.tsv
import fs from 'node:fs';
import path from 'node:path';

const argv = process.argv.slice(2);
if (argv.length !== 4 || argv[0] !== '--result' || argv[2] !== '--output') {
  throw Error('Usage: --result result.json --output cases.tsv');
}
const result = JSON.parse(fs.readFileSync(path.resolve(argv[1]), 'utf8'));
const output = path.resolve(argv[3]);
if (fs.existsSync(output)) throw Error('Output already exists; preserving evidence');

// ---- verbatim from triangulate_probe.mjs ----
function mulberry32(seed) {
  return () => {
    seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rnd = mulberry32(20261015);
const u = (a, b) => a + (b - a) * rnd();
function reference(ray, proj, pt) {
  const [ptx, pty, ptz] = pt;
  const x0 = proj[10] * ptz + proj[11] + proj[8] * ptx + proj[9] * pty;
  const x1 = 1.0 / x0;
  const x2 = proj[0] * ptx + proj[1] * pty + proj[2] * ptz + proj[3] - ray[0] * x0;
  const x3 = proj[4] * ptx + proj[5] * pty + proj[6] * ptz + proj[7] - ray[1] * x0;
  const x4 = Math.pow(x0, -2);
  const r = [x1 * x2, x1 * x3];
  const j = [
    x4 * (-proj[8] * x2 + x0 * (proj[0] - proj[8] * ray[0])),
    x4 * (-proj[9] * x2 + x0 * (proj[1] - proj[9] * ray[0])),
    x4 * (-proj[10] * x2 + x0 * (-proj[10] * ray[0] + proj[2])),
    x4 * (-proj[8] * x3 + x0 * (proj[4] - proj[8] * ray[1])),
    x4 * (-proj[9] * x3 + x0 * (proj[5] - proj[9] * ray[1])),
    x4 * (-proj[10] * x3 + x0 * (-proj[10] * ray[1] + proj[6])),
  ];
  return {r, j};
}
function rotation(ax, ay, az) {
  const [cx, sx, cy, sy, cz, sz] = [Math.cos(ax), Math.sin(ax), Math.cos(ay), Math.sin(ay), Math.cos(az), Math.sin(az)];
  return [
    [cy * cz, -cy * sz, sy],
    [sx * sy * cz + cx * sz, -sx * sy * sz + cx * cz, -sx * cy],
    [-cx * sy * cz + sx * sz, cx * sy * sz + sx * cz, cx * cy],
  ];
}
const vectors = [];
for (let n = 0; n < 64; ++n) {
  const R = rotation(u(-0.5, 0.5), u(-0.5, 0.5), u(-0.5, 0.5));
  const t = [u(-1, 1), u(-1, 1), u(-1, 1)];
  const proj = [R[0][0], R[0][1], R[0][2], t[0], R[1][0], R[1][1], R[1][2], t[1], R[2][0], R[2][1], R[2][2], t[2]];
  const pt = [u(-2, 2), u(-2, 2), u(3, 8)];
  const ray = [u(-0.6, 0.6), u(-0.6, 0.6)];
  vectors.push({ray, proj, pt});
}
// ---- end verbatim ----

if (result.results.length !== 128) throw Error('result.json must hold 128 cases');
for (const rec of result.results) {
  const ref = reference(vectors[rec.k].ray, vectors[rec.k].proj, vectors[rec.k].pt);
  if (!ref.r.every((x, i) => x === rec.refR[i])) throw Error(`refR mismatch at case ${rec.k}`);
  if (rec.withJac && !ref.j.every((x, i) => x === rec.refJ[i])) throw Error(`refJ mismatch at case ${rec.k}`);
}
const bits = (x) => {
  const d = new DataView(new ArrayBuffer(8));
  d.setFloat64(0, x, true);
  return d.getBigUint64(0, true).toString(16).padStart(16, '0');
};
const lines = ['# MB-TRI inputs regenerated by gen_triangulate_cases.mjs; verified bit-exact against ' +
               'result.json refR/refJ (128/128). Columns: k, ray[2], projection[12], point[3].'];
vectors.forEach((v, k) => {
  lines.push([k, v.ray.map(bits).join(','), v.proj.map(bits).join(','), v.pt.map(bits).join(',')].join('\t'));
});
fs.writeFileSync(output, lines.join('\n') + '\n');
console.log(`wrote ${vectors.length} input vectors; refR/refJ reproduced for ${result.results.length} cases`);
