#!/usr/bin/env python3
"""Generate src/config/config_defaults.inc from the recovered xr-slam config defaults.

Input: config-defaults.json (prior RE lane; entries {key, func, addr, args, getter}).
Rules (fixed before any engine result exists):
  * getter -> type: 458 = float, 851 = int, 881 = bool, 1131 = double (RE-A §2 row 4; S2 §4).
  * A key's default comes from the entries whose getter is one of the four above and whose args
    are exactly one typed literal. All such entries must agree, otherwise generation fails.
  * Keys without such an entry are emitted as SR_CONFIG_UNRECOVERED (no default, no struct field).
  * i32 literals are wrapped to int32 (the JSON stores them unsigned, e.g. 4294967295 = -1).
  * Keys never read by the binary (US-009 revision; S3 §4.3, S2 §4.2) are flagged read=false.
Output is deterministic; the file records the input sha256.

Usage: gen_config_defaults_inc.py <config-defaults.json> <out.inc>
"""
import hashlib
import json
import re
import struct
import sys
from collections import OrderedDict

GETTER_TYPES = {
    458: ("kFloat", "float", "f32"),
    851: ("kInt", "int", "i32"),
    881: ("kBool", "bool", "i32"),
    1131: ("kDouble", "double", "f64"),
}

# Registered but never read by the binary (load count 0): S3 §4.3 (4 keys), S2 §4.2 (2 keys).
UNREAD_KEYS = {
    "BundleAdjustment.cameraMotionWeight",
    "BundleAdjustment.numPreviousKeyframesToAdjust",
    "BundleAdjustment.minNumKeyframesForPointToAdjust",
    "MapBuilder.keyframeVariabilityCriterion",
    "WorldMaps.lostMatcherRadius",
    "WorldMaps.enableLostLocalMatcher",
}


def snake(name):
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    return s.lower()


def f32_literal(v):
    f = struct.unpack("<f", struct.pack("<f", v))[0]
    if f != v:
        raise SystemExit(f"not an exact f32 value: {v!r}")
    s = "%.9g" % f
    if not any(c in s for c in ".en"):
        s += ".0"
    return s + "f"


def f64_literal(v):
    s = repr(float(v))
    if not any(c in s for c in ".en"):
        s += ".0"
    return s


def i32_literal(v):
    v = int(v)
    if v >= 2**31:
        v -= 2**32
    if not -(2**31) <= v < 2**31:
        raise SystemExit(f"not an int32: {v}")
    return str(v)


def main():
    src, out = sys.argv[1], sys.argv[2]
    raw = open(src, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()
    entries = json.loads(raw)["entries"]

    by_key = OrderedDict()
    for e in entries:
        by_key.setdefault(e["key"], []).append(e)

    groups = OrderedDict()
    n_typed = n_unrec = 0
    for key in sorted(by_key):
        prefix, name = key.split(".", 1)
        es = by_key[key]
        cands = [e for e in es if e.get("getter") in GETTER_TYPES and len(e["args"]) == 1
                 and e["args"][0][0] in ("i32", "f32", "f64")]
        g = groups.setdefault(prefix, {"typed": [], "unrec": []})
        if not cands:
            hint = sorted({e["func"] for e in es})[0]
            g["unrec"].append((key, hint))
            n_unrec += 1
            continue
        sig = {(e["getter"], e["args"][0][0], e["args"][0][1]) for e in cands}
        if len(sig) != 1:
            raise SystemExit(f"conflicting defaults for {key}: {sorted(sig)}")
        getter, atype, value = sig.pop()
        kind, ctype, want = GETTER_TYPES[getter]
        if atype != want:
            raise SystemExit(f"{key}: getter {getter} expects {want}, literal is {atype}")
        if kind == "kFloat":
            lit = f32_literal(value)
        elif kind == "kDouble":
            lit = f64_literal(value)
        elif kind == "kBool":
            if int(value) not in (0, 1):
                raise SystemExit(f"{key}: bool literal {value}")
            lit = "true" if int(value) else "false"
        else:
            lit = i32_literal(value)
        owner = sorted({e["func"] for e in cands})[0]
        read = "false" if key in UNREAD_KEYS else "true"
        g["typed"].append((snake(name), key, kind, ctype, lit, getter, owner, read))
        n_typed += 1

    missing = UNREAD_KEYS - set(by_key)
    if missing:
        raise SystemExit(f"unread keys not in input: {sorted(missing)}")

    lines = [
        "// GENERATED by src/config/gen_config_defaults_inc.py. Do not edit.",
        f"// Input: config-defaults.json sha256 {sha}",
        f"// Keys: {n_typed + n_unrec} unique ({n_typed} typed defaults, {n_unrec} unrecovered).",
        "//",
        "// SR_CONFIG_BEGIN(Prefix) ... SR_CONFIG_END(Prefix) group the keys of one getter prefix.",
        "// SR_CONFIG_KEY(Prefix, field, \"Key\", ParamKind, c_type, default, getter_func,",
        "//               owner_func, read_by_binary)",
        "// SR_CONFIG_UNRECOVERED(Prefix, \"Key\", func) = key seen in the binary without a",
        "//               recoverable typed default (out of world-SLAM scope).",
        "// The includer defines all four macros.",
        "",
    ]
    for prefix, g in groups.items():
        if g["typed"]:
            lines.append(f"SR_CONFIG_BEGIN({prefix})")
            for field, key, kind, ctype, lit, getter, owner, read in g["typed"]:
                lines.append(f"SR_CONFIG_KEY({prefix}, {field}, \"{key}\", {kind}, {ctype}, {lit}, "
                             f"{getter}, {owner}, {read})")
            lines.append(f"SR_CONFIG_END({prefix})")
        for key, hint in g["unrec"]:
            lines.append(f"SR_CONFIG_UNRECOVERED({prefix}, \"{key}\", {hint})")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out}: {n_typed} typed, {n_unrec} unrecovered, sha256 {sha}")


if __name__ == "__main__":
    main()
