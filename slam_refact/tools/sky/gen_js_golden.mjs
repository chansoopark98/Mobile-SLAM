#!/usr/bin/env node
// Golden data for the pure functions of the original LayersController JS, produced by EXECUTING the
// original source text (assets/references/xr_reference/official/xr_reference/reality/app/xr/js/src/
// pixel-transforms.ts and quaternion.ts) in node (US-020; docs/spec/09-sky.md §5, gate SKY-G0).
//
//   node gen_js_golden.mjs --out <dir>      (refuses to overwrite)
//
// The .ts text is read from the reference checkout, type annotations are removed by a small, printed
// transformation (see strip()), and the resulting functions are run on deterministic inputs
// (32-bit LCG bytes). Output:
//   <dir>/preprocess_cases.tsv   name fn src_w src_h dst_w dst_h seed expected_sha256_of_dst
//   <dir>/quaternion_cases.tsv   alpha beta gamma x y z w   (17 significant digits)
//   <dir>/PROVENANCE.txt         sha256 of both .ts files, the stripped text, node version
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const args = process.argv.slice(2);
const out = args[args.indexOf('--out') + 1];
if (!out) throw new Error('--out <dir> required');
fs.mkdirSync(out, {recursive: false});
const base = path.join(root, 'assets/references/xr_reference/official/xr_reference/reality/app/xr/js/src');
const sha = b => crypto.createHash('sha256').update(b).digest('hex');
const ptSrc = fs.readFileSync(path.join(base, 'pixel-transforms.ts'));
const qtSrc = fs.readFileSync(path.join(base, 'quaternion.ts'));

// Removes the TypeScript-only text of these two files: `: type` annotations of parameters and return
// values, interface blocks and the export lists. Nothing else is touched.
function strip(text) {
  return text
    .replace(/interface Quaternion \{[^}]*\}/, '')
    .replace(/export \{[^}]*\}/g, '')
    .replace(/(\w+): (number|Uint8Array|Float32Array|Quaternion)(\[\])?(?=[,)\n= ])/g, '$1')
    .replace(/\): Quaternion =>/, ') =>');
}
const ptJs = strip(ptSrc.toString());
const qtJs = strip(qtSrc.toString());
const fn = new Function(ptJs + '\n' + qtJs +
  '\nreturn {toImageArrayLetterbox, toImageArrayRotateCW90, toImageArrayRotateCCW90,' +
  ' scaleFactorSameAspectRatioCrop, getQuaternion};')();

function lcgBytes(n, seed) {
  const a = new Uint8Array(n);
  let s = seed >>> 0;
  for (let i = 0; i < n; i++) {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    a[i] = s >>> 24;
  }
  return a;
}
const cases = [];
const shapes = [
  // [src_w, src_h, dst_w, dst_h]: the deployed use (portrait model input) and the original's quirks
  [144, 256, 144, 256], [256, 144, 144, 256], [144, 256, 256, 144], [100, 60, 144, 256],
  [96, 128, 144, 256], [143, 255, 144, 256], [145, 257, 144, 256], [60, 100, 100, 60],
  [31, 17, 32, 18], [17, 31, 32, 18], [1, 1, 1, 1], [5, 3, 4, 4],
];
let seed = 1;
for (const fnName of ['toImageArrayLetterbox', 'toImageArrayRotateCW90', 'toImageArrayRotateCCW90']) {
  for (const [sw, sh, dw, dh] of shapes) {
    const src = lcgBytes(sw * sh * 4, seed);
    const dst = new Uint8Array(dw * dh * 4);  // the controller fill(0)s it
    global.__x = 0;
    new Function('f', 'src', 'sw', 'sh', 'dw', 'dh', 'dst', 'f(src, sw, sh, dw, dh, dst)')(
      new Function(ptJs + `\nreturn ${fnName};`)(), src, sw, sh, dw, dh, dst);
    cases.push([fnName, sw, sh, dw, dh, seed, sha(Buffer.from(dst))]);
    seed++;
  }
}
fs.writeFileSync(path.join(out, 'preprocess_cases.tsv'),
  '# name\tsrc_w\tsrc_h\tdst_w\tdst_h\tseed\tsha256(dst bytes)\n' +
  cases.map(c => c.join('\t')).join('\n') + '\n');
const angles = [[0, 0, 0], [0, 90, 0], [90, 0, 0], [0, 0, 90], [30, 60, 10], [120, 110, -5], [359.5, 45.25, 17.5],
  [12.345, 98.7654, -0.123], [180, 180, 90], [-45, -90, -30], [NaN, 70, 5], [5, undefined, 3]];
const qrows = angles.map(([a, b, g]) => {
  const q = fn.getQuaternion(a, b, g);
  return [String(a), String(b), String(g), q.x, q.y, q.z, q.w].map(v => typeof v === 'number' ? v.toPrecision(17) : v).join('\t');
});
fs.writeFileSync(path.join(out, 'quaternion_cases.tsv'),
  '# alpha\tbeta\tgamma\tx\ty\tz\tw (JS getQuaternion, 17 significant digits; NaN/undefined inputs print as typed)\n' +
  qrows.join('\n') + '\n');
const sf = [[480, 640, 144, 256], [640, 480, 256, 144], [1080, 1920, 144, 256], [100, 100, 144, 256]]
  .map(a => [...a, fn.scaleFactorSameAspectRatioCrop(...a).toPrecision(17)].join('\t'));
fs.writeFileSync(path.join(out, 'scalefactor_cases.tsv'),
  '# image_w\timage_h\tdesired_w\tdesired_h\tscale (JS number, 17 digits)\n' + sf.join('\n') + '\n');
fs.writeFileSync(path.join(out, 'PROVENANCE.txt'),
  `generated by slam_refact/tools/sky/gen_js_golden.mjs (node ${process.version}) on ${new Date().toISOString()}\n` +
  `pixel-transforms.ts sha256 ${sha(ptSrc)}\nquaternion.ts sha256 ${sha(qtSrc)}\n` +
  `stripped pixel-transforms sha256 ${sha(Buffer.from(ptJs))}\nstripped quaternion sha256 ${sha(Buffer.from(qtJs))}\n` +
  'Reference checkout: assets/references/xr_reference/official/xr_reference (public commit 4edfa484, copyright line removed).\n' +
  'Inputs: 32-bit LCG bytes s=s*1664525+1013904223, byte = s>>24, seed per case in the tsv.\n');
console.log('cases', cases.length, 'quaternions', qrows.length);
