#!/usr/bin/env python3
"""Golden data for the calculator math of the hand module (US-021, gate HAND-G2): expected values from
tools/hand/hand_ref.py (a second implementation, numpy), inputs generated by an integer LCG that the
C++ test reproduces exactly (every raw value is (int(s >> 8) - 2^23) * 2^-20, exact in float32).

  gen_geometry_golden.py --out <new dir>
    anchors.f32            2944 x 4 float32 (x_center, y_center, w, h)
    detect_cases.tsv       seed, then lines of "det ..." per retained detection (after NMS + letterbox removal)
    rect_cases.tsv         detection -> rect -> transformed rect cases
    landmark_cases.tsv     letterbox removal + projection + landmarks->detection cases
"""
import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hand_ref as H  # noqa: E402

f32 = np.float32


def lcg_values(n, seed):
  s = seed & 0xFFFFFFFF
  out = np.empty(n, np.float64)
  for i in range(n):
    s = (s * 1664525 + 1013904223) & 0xFFFFFFFF
    out[i] = (int(s >> 8) - (1 << 23)) * 2.0 ** -20  # in [-8, 8)
  return out.astype(np.float32)


def planted(seed):
  """Raw palm model outputs: noise, plus a few planted objects (high scores, plausible boxes)."""
  boxes = lcg_values(2944 * 18, seed).reshape(2944, 18) * f32(4.0)  # noise in [-32, 32)
  scores = lcg_values(2944, seed + 1000) * f32(0.5) - f32(4.0)      # raw scores around -4 (sigmoid 0.02)
  rng = np.random.default_rng(seed)
  centers = [int(c) for c in rng.integers(0, 2944 - 20, size=3)]
  for center in centers:
    for j in range(8):  # a cluster of overlapping anchors
      i = int(center) + j
      scores[i] = f32(2.0 + 0.3 * j)
      boxes[i, 0:2] = f32(0.0)
      boxes[i, 2:4] = f32(60.0 + 3 * j)
      boxes[i, 4:18] = (lcg_values(14, seed + 7 * j) * f32(2.0)).astype(np.float32)
  return boxes.astype(np.float32), scores.astype(np.float32), centers


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument('--out', required=True)
  ap.add_argument('--mode', choices=['golden', 'gate'], default='golden',
                  help='golden: the fixed cases checked in under tests/hand/golden-geometry; gate: fresh cases from '
                       '--seed (preregistered gate HAND-G2)')
  ap.add_argument('--seed', type=int, default=0)
  ap.add_argument('--detect-count', type=int, default=6)
  ap.add_argument('--rect-count', type=int, default=60)
  ap.add_argument('--landmark-count', type=int, default=40)
  a = ap.parse_args()
  os.makedirs(a.out, exist_ok=False)
  anchors = H.generate_anchors()
  assert anchors.shape == (2944, 4), anchors.shape
  anchors.astype(np.float32).tofile(os.path.join(a.out, 'anchors.f32'))
  lines = []
  detect_seeds = (11, 12, 13, 14) if a.mode == 'golden' else tuple(a.seed * 100 + i for i in range(a.detect_count))
  for seed in detect_seeds:
    boxes, scores, centers = planted(seed)
    dets = H.decode_and_filter(boxes, scores, anchors)
    nms = H.weighted_nms(dets)
    pad = [0.234, 0.0, 0.234, 0.0] if seed % 2 == 0 else [0.0, 0.1, 0.0, 0.1]
    final = H.remove_letterbox_det(nms, pad)
    lines.append('case\t%d\t%d\t%d\t%r\t%r\t%r\t%r\t%d\t%d\t%d' % (seed, len(dets), len(final), *pad, *centers))
    for d in final:
      lines.append('det\t%r\t%r\t%r\t%r\t%r\t' % (d['score'], d['xmin'], d['ymin'], d['w'], d['h']) + '\t'.join('%r\t%r' % kp for kp in d['kp']))
  open(os.path.join(a.out, 'detect_cases.tsv'), 'w').write(
      '# case: seed, #decoded (>=0.5), #retained, letterbox padding l t r b, three cluster centres; det: score xmin ymin w h kp0x kp0y .. kp6y\n' + '\n'.join(lines) + '\n')
  rng = np.random.default_rng(5 if a.mode == 'golden' else a.seed)
  n_rect = 24 if a.mode == 'golden' else a.rect_count
  n_landmark = 12 if a.mode == 'golden' else a.landmark_count
  rc = []
  for _ in range(n_rect):
    iw, ih = int(rng.integers(100, 700)), int(rng.integers(100, 700))
    d = dict(score=0.9, xmin=float(f32(rng.uniform(0.05, 0.6))), ymin=float(f32(rng.uniform(0.05, 0.6))),
             w=float(f32(rng.uniform(0.05, 0.3))), h=float(f32(rng.uniform(0.05, 0.3))),
             kp=[(float(f32(rng.uniform(0.0, 1.0))), float(f32(rng.uniform(0.0, 1.0)))) for _ in range(10)])
    r = H.detection_to_rect(d, iw, ih, 0, 2, 90.0)
    palm = H.transform_rect(r, iw, ih, 2.6, 2.6, 0.0, -0.5, True)
    nxt = H.transform_rect(H.detection_to_rect(d, iw, ih, 0, 9, 90.0), iw, ih, 1.6, 1.6, 0.0, 0.0, True)
    rc.append('\t'.join([str(iw), str(ih), *['%r' % v for v in (d['xmin'], d['ymin'], d['w'], d['h'])],
                         *['%r\t%r' % kp for kp in d['kp']],
                         *['%r' % v for v in (r['x'], r['y'], r['w'], r['h'], r['rot'])],
                         *['%r' % v for v in (palm['x'], palm['y'], palm['w'], palm['h'], palm['rot'])],
                         *['%r' % v for v in (nxt['x'], nxt['y'], nxt['w'], nxt['h'], nxt['rot'])]]))
  open(os.path.join(a.out, 'rect_cases.tsv'), 'w').write(
      '# iw ih xmin ymin w h kp0x kp0y .. kp9y | rect(x y w h rot) of keypoints 0->2 | palm rect after RectTransformation(2.6, shift_y -0.5, square_long) | '
      'next rect of keypoints 0->9 after RectTransformation(1.6, square_long)\n' + '\n'.join(rc) + '\n')
  lc = []
  for _ in range(n_landmark):
    lms = [(float(f32(rng.uniform(0.0, 1.0))), float(f32(rng.uniform(0.0, 1.0))), float(f32(rng.uniform(-60, 60)))) for _ in range(21)]
    pad = [0.0, 0.0, 0.0, 0.0] if rng.random() < 0.3 else [float(f32(rng.uniform(0, 0.25)))] * 2 + [0.0, 0.0]
    pad = [pad[0], pad[2], pad[1], pad[3]] if len(pad) == 4 else pad
    r = dict(x=float(f32(rng.uniform(0.2, 0.8))), y=float(f32(rng.uniform(0.2, 0.8))), w=float(f32(rng.uniform(0.2, 0.9))),
             h=float(f32(rng.uniform(0.2, 0.9))), rot=float(f32(rng.uniform(-3.1, 3.1))))
    unbox = H.remove_letterbox_landmarks(lms, pad)
    proj = H.project_landmarks(unbox, r)
    det = H.landmarks_to_detection(proj)
    lc.append('\t'.join([*['%r' % v for v in pad], *['%r' % v for v in (r['x'], r['y'], r['w'], r['h'], r['rot'])],
                         *['%r\t%r\t%r' % l for l in lms], *['%r\t%r\t%r' % l for l in proj],
                         *['%r' % v for v in (det['xmin'], det['ymin'], det['w'], det['h'])]]))
  open(os.path.join(a.out, 'landmark_cases.tsv'), 'w').write(
      '# pad(l t r b) | rect(x y w h rot) | 21 landmarks (x y z) | 21 projected landmarks after letterbox removal (x y z) | landmarks_to_detection bbox (xmin ymin w h)\n'
      + '\n'.join(lc) + '\n')
  open(os.path.join(a.out, 'PROVENANCE.txt'), 'w').write(
      'generated by slam_refact/tools/hand/gen_geometry_golden.py (expected values: tools/hand/hand_ref.py, numpy %s)\n'
      'LCG: s = s * 1664525 + 1013904223 (mod 2^32); raw value = (int(s >> 8) - 2^23) * 2^-20\n'
      'planted(seed): boxes = noise * 4, scores = noise * 0.5 - 4, three clusters of 8 overlapping anchors with raw score 2.0 + 0.3 j\n' % np.__version__)
  print('detect cases', len(detect_seeds), 'rect', len(rc), 'landmark', len(lc))


if __name__ == '__main__':
  main()
