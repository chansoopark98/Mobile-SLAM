#!/usr/bin/env python3
"""Extract the WebGL2 (#version 300 es) gr8 shaders embedded in the original xr-slam.wasm.

The original page compiles these exact strings (SPIRV-Cross rewrites of the public
reality/engine/features/gr8-*.{vert,frag}, gr8-feature-shader.cc:61-80) for its GPU pyramid
(gl-reality-frame.cc). The measurement page reuses them verbatim for its WebGL2 pyramid
(web/js/slam-refact-gr8gl.js), so the GPU frontend runs the original's shader code, not a port.

Each shader is a NUL-terminated string in the data section. They are identified by content (the
uniform/attribute set of each public shader), not by offset, and the script fails unless exactly
one string matches each signature.

  python3 -I slam_refact/tools/re/spec_frontend/extract_gr8_shaders.py \
      --wasm build/slam-refact-20261015/inputs/xr-slam.wasm --out web/js/slam-refact-gr8-shaders.js
"""

import argparse
import hashlib
import json
import re
import sys

EXPECTED_WASM_SHA256 = '780731fe294a725acf1b7717ed5ffb07ad9f0929e408a1d74f47450c291ec422'

# name -> (required substrings, forbidden substrings); public source file in the comment.
SIGNATURES = {
    # gr8-noop.vert
    'noopVert': (['in vec3 position;', 'in vec2 uv;', 'texUv = uv;'], ['uniform', 'precision']),
    # gr8-rotate.vert
    'rotateVert': (['uniform mat4 mvp;', 'uniform int flipY;', 'uniform mediump int rotation;'], []),
    # gr8-rotate-only.vert
    'rotateOnlyVert': (['uniform int rotation;', 'in vec3 position;'], ['mvp', 'flipY']),
    # gr8-input.frag (3x3 blur, sigma 0.75)
    'inputFrag': (['uniform mediump sampler2D sampler;', '0.2689580023288726806640625'], ['roi']),
    # gr8-pyramid-blur.frag (3x3 blur, sigma 0.72)
    'pyramidBlurFrag': (['uniform mediump sampler2D texSampler;', 'uniform vec4 roi;',
                         '0.283464014530181884765625'], []),
    # gr8-pyramid-decimate.frag (bilinear decimation)
    'pyramidDecimateFrag': (['uniform vec4 roi;', 'floor(', 'mix(mix('], ['texSampler']),
    # gr8-stage1.frag (gray, ROI clear, curvy targets)
    'stage1Frag': (['uniform mediump int clear;', 'uniform mediump int isCurvy;'], []),
    # gr8-stage2.frag (FAST-9 score packing)
    'stage2Frag': (['uniform mediump sampler2D sampler;', 'uniform vec2 scale;'],
                   ['roi', 'clear', 'nmsTolerance', 'pixScale', '0.2689580023288726806640625']),
    # gr8-stage3.frag (NMES + subpixel)
    'stage3Frag': (['uniform float nmsTolerance;', 'uniform float scoreThresh;', 'subpixelQ'], []),
}


def strings_from(data, marker=b'#version 300 es'):
    for m in re.finditer(re.escape(marker), data):
        end = data.index(b'\0', m.start())
        yield m.start(), data[m.start():end].decode('utf-8')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--wasm', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    data = open(a.wasm, 'rb').read()
    wasm_sha = hashlib.sha256(data).hexdigest()
    if wasm_sha != EXPECTED_WASM_SHA256:
        sys.exit(f'unexpected wasm sha256 {wasm_sha}')
    found = {}
    candidates = list(strings_from(data))
    for name, (need, avoid) in SIGNATURES.items():
        hits = [(o, s) for o, s in candidates
                if all(n in s for n in need) and not any(x in s for x in avoid)]
        if len(hits) != 1:
            sys.exit(f'{name}: {len(hits)} matching shader strings (want exactly 1)')
        found[name] = hits[0]
    offsets = sorted(o for o, _ in found.values())
    if len(set(offsets)) != len(offsets):
        sys.exit('two signatures matched the same string')
    lines = [
        '// GENERATED by slam_refact/tools/re/spec_frontend/extract_gr8_shaders.py. Do not edit.',
        '// WebGL2 gr8 shaders exactly as embedded in the original reference runtime xr-slam.wasm',
        f'// (sha256 {wasm_sha}); SPIRV-Cross forms of the public',
        '// reality/engine/features/gr8-*.{vert,frag} (xr_reference/xr_reference@4edfa484).',
        f'export const GR8_SHADER_SOURCE_WASM_SHA256 = {json.dumps(wasm_sha)};',
    ]
    meta = {}
    for name in SIGNATURES:
        off, src = found[name]
        meta[name] = {'offset': off, 'bytes': len(src.encode()), 'sha256': hashlib.sha256(src.encode()).hexdigest()}
        lines.append(f'export const {name} = {json.dumps(src)};')
    lines.append(f'export const GR8_SHADER_META = {json.dumps(meta, sort_keys=True)};')
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print(json.dumps({'wasm_sha256': wasm_sha, 'out': a.out, 'shaders': meta}, indent=1))


if __name__ == '__main__':
    main()
