#!/usr/bin/env python3
"""Generates run_lcgold_scene.mjs from ../../../re/runtime/us025/run_lcgold.mjs by exact text hunks (each asserted to apply exactly once).
Only differences: relative import/dir paths (the copy lives in harness/us025/scene) and the scenario file, which is $US025_SCENARIOS (a JSON
file with the same shape as tools/re/runtime/scenarios.json) instead of the shared scenarios.json (not modified by this lane).
usage: make_runner.py"""
import pathlib
HERE = pathlib.Path(__file__).resolve().parent
src = (HERE.parents[2] / 're/runtime/us025/run_lcgold.mjs').read_text()


def sub(old, new):
    global src
    assert src.count(old) == 1, (src.count(old), old[:90])
    src = src.replace(old, new)


src = ('// GENERATED by make_runner.py from tools/re/runtime/us025/run_lcgold.mjs (do not edit): scenario file from $US025_SCENARIOS, paths adjusted.\n') + src
sub("from '../capnp-event-queue.mjs'", "from '../../../re/runtime/capnp-event-queue.mjs'")
sub("const usdir = path.dirname(fileURLToPath(import.meta.url));", "const usdir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../re/runtime/us025');")
sub("const scenarios = JSON.parse(await fs.readFile(path.join(here, 'scenarios.json'), 'utf8'));",
    "const scenarios = JSON.parse(await fs.readFile(process.env.US025_SCENARIOS || path.join(here, 'scenarios.json'), 'utf8'));")
(HERE / 'run_lcgold_scene.mjs').write_text(src)
print('wrote run_lcgold_scene.mjs')
